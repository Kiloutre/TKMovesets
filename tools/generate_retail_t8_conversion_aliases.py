"""Package the existing ID evidence for conversion diagnostics, without enabling rules."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'TKMovesets2/GameSpecific/MovesetConverters/RetailT8Aliases.inc'


def generate():
    catalog = json.loads((ROOT / 'research/t7-to-retail-t8-aliases.json').read_text(encoding='utf-8'))
    review = json.loads((ROOT / 'research/retail-t8-handler-review.json').read_text(encoding='utf-8'))
    for source in (catalog, review):
        if source['target_game'] != 't8-retail' or source['target_build'] != '26155785' or source['runtime_enabled']:
            raise ValueError('Unexpected alias evidence profile')
    rows = {}
    for row in catalog['entries']:
        if row['runtime_enabled'] or row['parameter_transform'] is not None:
            raise ValueError('ID evidence must not enable parameter conversion')
        key = (row['category'] == 'extra_property', row['t7_id'])
        if row['category'] not in ('requirement', 'extra_property') or key in rows:
            raise ValueError('Unknown category or duplicate source ID')
        status = row.get('effective_status', row['status'])
        # An unresolved route conflict keeps its evidence status but has no
        # selected diagnostic target. Interpolation/weak selections stay explicit.
        target = row['review_retail_id'] if status not in ('conflict', 'unmapped') else None
        rows[key] = (target, status, 'alias_catalog')
    selections = {}
    for row in review['entries']:
        if row['runtime_enabled'] or row['parameter_transform'] is not None:
            raise ValueError('Handler ID evidence must not enable parameter conversion')
        if row['category'] not in ('requirements', 'properties'):
            raise ValueError('Unknown handler category')
        target = row.get('selected_retail_id')
        if target is None:
            continue
        key = (row['category'] == 'properties', row['source_id'])
        if key in selections and selections[key] != target:
            raise ValueError('Conflicting handler selections')
        selections[key] = target
    for key, target in selections.items():
        rows[key] = (target, 'handler_supported_id_alignment', 'handler_review')
    lines = ['// Generated by tools/generate_retail_t8_conversion_aliases.py.',
             '// ID evidence only; no parameter transforms or runtime authorization.']
    for (prop, source), (target, status, provenance) in sorted(rows.items()):
        if not 0 <= source < 0xffffffff or (target is not None and not 0 <= target < 0xffffffff):
            raise ValueError('ID outside supported range')
        lines.append('    {%s, %du, %s, "%s", "%s"},' %
                     ('true' if prop else 'false', source,
                      'UINT32_MAX' if target is None else f'{target}u', status, provenance))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Packaged conversion ID evidence is stale')
    else:
        OUTPUT.write_text(content, encoding='utf-8')
    print('Conversion ID evidence packaged; parameter rules unchanged.')


if __name__ == '__main__':
    main()
