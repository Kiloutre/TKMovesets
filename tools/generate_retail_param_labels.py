"""Write the retail T8 parameter-meaning files from the handler review CSVs of the Tekken8 cnt project.

Usage: python tools/generate_retail_param_labels.py <path to Tekken8 cnt/docs/retail-moveset>

Output (read by the retail editor, EditorVisuals_t8Retail.cpp RetailParamLabels):
  TKMovesets2/Resources/TKMInterface/editor_t8-retail_requirement_params.txt
  TKMovesets2/Resources/TKMInterface/editor_t8-retail_property_params.txt
One tab-separated line per id: id, handler name, first-parameter meaning, confidence, common values, meaning.
Rows with neither a parameter description nor a meaning are skipped."""
import csv
import pathlib
import sys

SOURCES = {
    "requirements_retail.csv": "editor_t8-retail_requirement_params.txt",
    "extraprops_retail.csv": "editor_t8-retail_property_params.txt",
}


def clean(text):
    return " ".join(text.replace("\t", " ").split())


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1])
    target = pathlib.Path(__file__).resolve().parent.parent / "TKMovesets2" / "Resources" / "TKMInterface"
    for name, output in SOURCES.items():
        rows = list(csv.DictReader(open(source / name, encoding="utf-8", newline="")))
        lines = ["# id\tname\tparameter 1\tconfidence\tcommon values\tmeaning  (generated by tools/generate_retail_param_labels.py from "
                 + name + ")"]
        kept = 0
        for row in rows:
            if not clean(row["param"]) and not clean(row["meaning"]):
                continue
            lines.append("\t".join([clean(row["id"]), clean(row["name"]), clean(row["param"]), clean(row["confidence"]),
                                    clean(row["top_params"]), clean(row["meaning"])]))
            kept += 1
        (target / output).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"{output}: {kept} of {len(rows)} ids")


if __name__ == "__main__":
    main()
